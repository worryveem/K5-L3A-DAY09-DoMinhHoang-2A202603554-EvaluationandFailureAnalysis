"""Reproduce the complete local Lab 9 checks, without committing or publishing anything.

Run from src/: python -m lab9.verify
All reports and logs are generated by commands; a non-zero result stops verification.
Expected rejections (helpful judge, regressions and traps) must exit 1 with a verdict.
"""

from __future__ import annotations

from datetime import datetime, timedelta, timezone
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import time

from lab8.console import utf8_stdio

SRC = Path(__file__).resolve().parents[1]
ROOT = SRC.parent
REPORTS = SRC / "reports"


def fingerprint() -> str:
    paths = set()
    for pattern in ("lab9/*.py", "lab8/**/*.py", "config/*.yaml", "tests/test_lab9*.py", "requirements*.txt"):
        paths.update(SRC.glob(pattern))
    paths.add(ROOT / ".github/workflows/eval-gate.yml")
    digest = hashlib.sha256()
    for path in sorted(paths):
        digest.update(path.relative_to(ROOT).as_posix().encode())
        digest.update(path.read_bytes().replace(b"\r\n", b"\n"))
    return digest.hexdigest()


def main() -> int:
    utf8_stdio()
    if Path.cwd().resolve() != SRC:
        raise SystemExit("Run python -m lab9.verify from src/")
    REPORTS.mkdir(exist_ok=True)
    started = datetime.now(timezone(timedelta(hours=7)))
    summary = {"run_id": f"V-{started:%Y%m%d-%H%M%S}", "started_at": started.isoformat(),
               "code_sha256": fingerprint(), "passed": False, "github_actions_executed": False,
               "committed_or_pushed": False, "steps": []}
    env = {**os.environ, "PYTHONUTF8": "1", "PYTHONIOENCODING": "utf-8", "NO_COLOR": "1"}

    def run(args: list[str], expected: int = 0, contains: tuple[str, ...] = ()) -> str:
        print(f"[{len(summary['steps']) + 1}] python {' '.join(args)} (expect {expected})", flush=True)
        before = time.monotonic()
        result = subprocess.run([sys.executable, *args], cwd=SRC, env=env, capture_output=True,
                                text=True, encoding="utf-8", errors="replace")
        output = result.stdout + result.stderr
        record = {"args": args, "expected_exit": expected, "actual_exit": result.returncode,
                  "seconds": round(time.monotonic() - before, 2), "output": output}
        summary["steps"].append(record)
        print("\n".join(output.strip().splitlines()[-6:]), flush=True)
        if result.returncode != expected or any(token not in output for token in contains):
            raise RuntimeError(f"Unexpected result for {' '.join(args)}; inspect verification_summary.json")
        return output

    def gate(pr: str, baseline: str, spec: str, reference: str, expected: int, *tokens: str) -> str:
        return run(["-m", "lab9.gate", "--pr", pr, "--baseline", baseline, "--spec", spec,
                    "--base-spec", reference], expected, (f"exit {expected}", *tokens))

    try:
        protected = ["src/lab8", "src/data/public_claims.jsonl", "src/data/public_world_state.json",
                     "src/lab9/variants.py", "src/lab9/variant_agent.py", "src/lab9/traps.py",
                     "src/tests/test_lab9_stats.py", "src/tests/test_lab9_graders.py", "src/tests/test_lab9_advanced.py"]
        subprocess.run(["git", "diff", "--exit-code", "HEAD", "--", *protected], cwd=ROOT, check=True)
        summary["reference_commit"] = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
        summary["working_tree_dirty"] = bool(subprocess.check_output(["git", "status", "--porcelain"], cwd=ROOT))
        for version, source in (("v1", "metric_spec.yaml"), ("v2", "metric_spec_v2.yaml")):
            policy = subprocess.check_output(["git", "show", f"HEAD:src/config/{source}"], cwd=ROOT)
            (REPORTS / f"reference_metric_spec_{version}.yaml").write_bytes(policy)
        run(["-m", "lab9.smoke"], contains=("M0 PASS",))
        run(["-m", "lab9.evalset", "--build", "--check"], contains=("0 problem(s)",))
        run(["-m", "lab9.evalset", "--v2", "--build"], contains=("0 problem(s)",))
        run(["-m", "pytest", "-q"])
        run(["-m", "pytest", "-q", "-m", "student", "-o", "addopts=", "-k", "lab9"])
        run(["-m", "pytest", "-q", "-m", "student", "-o", "addopts=", "-k", "swarm"])
        for name, expected in (("tone", 0), ("helpful", 1)):
            run(["-m", "lab9.judge", "--csv", f"data/eval/judge_{name}_public.csv", "--audit", "5",
                 "--out", f"reports/judge_{name}_calibration.json"], expected,
                ("PASS floors" if expected == 0 else "FAIL floors",))
        run(["-m", "lab9.taxonomy_evidence"])
        v1, v2 = "config/metric_spec.yaml", "config/metric_spec_v2.yaml"
        b1, b2 = "reports/baseline_v1.json", "reports/baseline_v2.json"
        p1, p2 = "reports/reference_metric_spec_v1.yaml", "reports/reference_metric_spec_v2.yaml"
        for shape, output in (("swarm", b1), ("swarm", "reports/eval_pr.json"),
                              ("fixed", "reports/eval_fixed.json"), ("seeded_regression", "reports/eval_seeded_regression.json")):
            run(["-m", "lab9.eval", "--shape", shape, "--spec", v1, "--out", output])
        gate(b1, b1, v1, p1, 0)
        gate("reports/eval_pr.json", b1, v1, p1, 0)
        run(["-m", "lab9.ci_check", "--pr", "reports/eval_pr.json", "--baseline", b1, "--spec", v1])
        gate("reports/eval_fixed.json", b1, v1, p1, 0)
        summary["core_regression_output"] = gate("reports/eval_seeded_regression.json", b1, v1, p1, 1, "pass_rate")
        summary["detection_output"] = run(["-m", "lab9.mutation", "--detect"], contains=("detection", "false alarms"))
        run(["-m", "lab9.eval", "--shape", "swarm", "--spec", v2, "--out", b2])
        gate(b2, b2, v2, p2, 0)
        summary["mutation_output"] = run(["-m", "lab9.mutation", "--spec", v2, "--baseline", b2,
                                          "--base-spec", p2], contains=("mutation score 3/3", "false alarms 0"))
        summary["aa_output"] = run(["-m", "lab9.mutation", "--spec", v2, "--aa", "66,77,88,99,110"])
        aa_deltas = {}
        for line in summary["aa_output"].splitlines():
            columns = line.split()
            if len(columns) == 4 and columns[0] not in ("metric",):
                aa_deltas[columns[0]] = float(columns[-1])
        if not aa_deltas or any(delta != 0 for delta in aa_deltas.values()):
            raise RuntimeError("Unexpected non-zero A/A noise on this deterministic MockLLM")
        summary["aa_deltas"] = aa_deltas
        for shape, token in (("slice_regression", "slice:money_movement/pass_rate"), ("flaky_regression", "pass_hat_5")):
            output = f"reports/v2/eval_{shape}.json"
            run(["-m", "lab9.eval", "--shape", shape, "--spec", v2, "--out", output])
            gate(output, b2, v2, p2, 1, token)
        run(["-m", "lab9.traps", "--pr", "reports/v2/eval_slice_regression.json", "--baseline", b2,
             "--spec", v2], contains=("exit 0", "blocked every public trap"))
        summary["trap_outputs"] = {}
        for trap in ("evaluator_errors_as_nan", "dropped_failing_rows", "cherry_picked_seeds", "loosened_spec"):
            policy = f"reports/traps/{trap}.spec.yaml" if trap == "loosened_spec" else v2
            summary["trap_outputs"][trap] = gate(f"reports/traps/{trap}.json", b2, policy, v2, 1, "INTEGRITY")
        for name in ("baseline_v1", "baseline_v2", "eval_fixed", "eval_seeded_regression"):
            report = json.loads((REPORTS / f"{name}.json").read_text(encoding="utf-8"))
            summary.setdefault("reports", {})[name] = {key: report[key] for key in ("run_id", "manifest", "metrics")}
        resolved = subprocess.check_output([sys.executable, "-m", "pip", "freeze"], text=True, encoding="utf-8")
        (REPORTS / "requirements-resolved.txt").write_text(resolved, encoding="utf-8")
        if fingerprint() != summary["code_sha256"]:
            raise RuntimeError("Source code changed during verification; rerun with a stable working tree")
        summary["passed"] = True
    except (RuntimeError, subprocess.CalledProcessError) as exc:
        summary["error"] = str(exc)
        print(f"FAILED: {exc}", flush=True)
    finally:
        summary["finished_at"] = datetime.now(timezone(timedelta(hours=7))).isoformat()
        path = REPORTS / "verification_summary.json"
        path.write_text(json.dumps(summary, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")
        sections = [f"$ python {' '.join(step['args'])}\nexpected={step['expected_exit']} actual={step['actual_exit']}\n{step['output']}"
                    for step in summary["steps"]]
        (REPORTS / "verification.log").write_text("\n\n".join(sections), encoding="utf-8")
    if summary["passed"]:
        draft = ["# Nội dung PR dự thảo — Lab 09\n",
                 "Hoàn thiện M0–M7: eval set, taxonomy, judge calibration, code graders, paired gate, slice/stability và integrity/ratchet.\n",
                 "Các kiểm tra dưới đây chạy tại máy; chưa commit/push và chưa chạy GitHub Actions.\n",
                 f"Verification: `{summary['run_id']}`; code SHA256 `{summary['code_sha256']}`.\n"]
        for title, output in (("Core: seeded regression bị chặn", summary["core_regression_output"]),
                              ("M3 detection", summary["detection_output"]), ("Mutation scorecard", summary["mutation_output"]),
                              ("A/A", summary["aa_output"]), *summary["trap_outputs"].items()):
            draft.extend([f"\n## {title}\n", f"```text\n{output.rstrip()}\n```\n"])
        (ROOT / "docs/PR_DESCRIPTION.md").write_text("\n".join(draft), encoding="utf-8")
    print(f"{'PASS' if summary['passed'] else 'FAIL'} {summary['run_id']} — {path}", flush=True)
    return 0 if summary["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
